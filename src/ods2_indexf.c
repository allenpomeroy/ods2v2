#include "ods2_indexf.h"

uint32_t ods2_indexf_header_lbn(const ods2_home_t *home, unsigned file_number)
{
    uint32_t m = home->ibmapsize; /* bitmap size in blocks */
    return home->ibmaplbn + (m + file_number - 1);
}
